def egress_envelope(obj: Any, where: str) -> str:
    generation, sequence, attempt, payload = take(
        obj, "generation", "sequence", "attempt", "payload", where=where
    )
    return (
        "{ generation := " + nat(generation, where) + ", sequence := " + nat(sequence, where)
        + ", attempt := " + nat(attempt, where) + ", payload := " + nat(payload, where) + " }"
    )


def egress_retry(obj: Any, where: str) -> str:
    if obj is None:
        return "none"
    sequence, attempt, backoff, exhausted = take(
        obj, "sequence", "attempt", "backoff", "exhausted", where=where
    )
    return (
        "(some { sequence := " + nat(sequence, where) + ", attempt := " + nat(attempt, where)
        + ", backoff := " + nat(backoff, where) + ", exhausted := " + boolean(exhausted, where)
        + " })"
    )


def egress_op(obj: Any, where: str) -> str:
    kind = obj.get("type") if isinstance(obj, dict) else None
    if kind == "enqueue":
        _, payload = take(obj, "type", "payload", where=where)
        return f".enqueue {nat(payload, where)}"
    if kind == "claim":
        _, generation = take(obj, "type", "generation", where=where)
        return f".claim {nat(generation, where)}"
    if kind == "ack":
        _, generation, through = take(obj, "type", "generation", "through", where=where)
        return f".ack {nat(generation, where)} {nat(through, where)}"
    if kind == "fail":
        _, generation, sequence = take(obj, "type", "generation", "sequence", where=where)
        return f".fail {nat(generation, where)} {nat(sequence, where)}"
    if kind == "retry_now":
        _, generation, sequence = take(obj, "type", "generation", "sequence", where=where)
        return f".retryNow {nat(generation, where)} {nat(sequence, where)}"
    if kind == "reconnect":
        _, generation = take(obj, "type", "generation", where=where)
        return f".reconnect {nat(generation, where)}"
    raise BridgeError(f"{where}: unknown egress op {obj!r}")


def egress_returns(obj: Any, where: str) -> str:
    if not isinstance(obj, dict) or not obj:
        raise BridgeError(f"{where}: expected a non-empty returns object")
    if "sequence" in obj and len(obj) == 1:
        return f".sequence {nat(obj['sequence'], where)}"
    if "claim" in obj:
        status = obj["claim"]
        if status == "claimed":
            _, envelope = take(obj, "claim", "envelope", where=where)
            return f".claim (.claimed {egress_envelope(envelope, where)})"
        if status == "empty":
            take(obj, "claim", where=where)
            return ".claim .empty"
        if status == "window_full":
            take(obj, "claim", where=where)
            return ".claim .windowFull"
        if status == "stale_generation":
            _, current = take(obj, "claim", "current", where=where)
            return f".claim (.staleGeneration {nat(current, where)})"
    if "ack" in obj:
        status = obj["ack"]
        if status == "advanced":
            _, through = take(obj, "ack", "through", where=where)
            return f".ack (.advanced {nat(through, where)})"
        if status == "unchanged":
            _, through = take(obj, "ack", "through", where=where)
            return f".ack (.unchanged {opt_nat(through, where)})"
        if status == "beyond_sent":
            _, next_sequence = take(obj, "ack", "next_sequence", where=where)
            return f".ack (.beyondSent {nat(next_sequence, where)})"
        if status == "stale_generation":
            _, current = take(obj, "ack", "current", where=where)
            return f".ack (.staleGeneration {nat(current, where)})"
    if "failure" in obj:
        status = obj["failure"]
        if status in ("retrying", "exhausted"):
            _, retry = take(obj, "failure", "retry", where=where)
            inner = egress_retry(retry, where)
            if inner == "none":
                raise BridgeError(f"{where}: {status} needs a retry record")
            return f".fail (.{status} {inner[len('(some '):-1]})"
        if status == "unknown_sequence":
            take(obj, "failure", where=where)
            return ".fail .unknownSequence"
        if status == "stale_generation":
            _, current = take(obj, "failure", "current", where=where)
            return f".fail (.staleGeneration {nat(current, where)})"
    if "retry_action" in obj:
        status = obj["retry_action"]
        if status == "scheduled":
            _, sequence = take(obj, "retry_action", "sequence", where=where)
            return f".retry (.scheduled {nat(sequence, where)})"
        if status == "unknown_sequence":
            take(obj, "retry_action", where=where)
            return ".retry .unknownSequence"
        if status == "stale_generation":
            _, current = take(obj, "retry_action", "current", where=where)
            return f".retry (.staleGeneration {nat(current, where)})"
    if "reconnect" in obj:
        status = obj["reconnect"]
        if status == "advanced":
            _, generation, replayed = take(obj, "reconnect", "generation", "replayed", where=where)
            return f".reconnect (.advanced {nat(generation, where)} {nat(replayed, where)})"
        if status == "unchanged":
            _, generation = take(obj, "reconnect", "generation", where=where)
            return f".reconnect (.unchanged {nat(generation, where)})"
        if status == "stale_generation":
            _, current = take(obj, "reconnect", "current", where=where)
            return f".reconnect (.staleGeneration {nat(current, where)})"
    raise BridgeError(f"{where}: unknown egress returns {obj!r}")


def egress_step(step: Any, where: str) -> str:
    op, returns, expected = take(step, "op", "returns", "expected", where=where)
    (generation, next_sequence, pending, inflight, acked_through, retry, invalidates) = take(
        expected,
        "generation",
        "next_sequence",
        "pending",
        "inflight",
        "acked_through",
        "retry",
        "invalidates",
        where=f"{where}.expected",
    )
    inv = take(invalidates, "pending", "inflight", "acked_through", "retry", where=f"{where}.invalidates")
    ind = "      "
    pend = lean_list([egress_envelope(e, f"{where}.pending") for e in pending], ind)
    infl = lean_list([egress_envelope(e, f"{where}.inflight") for e in inflight], ind)
    return (
        "{ op := " + egress_op(op, f"{where}.op") + "\n"
        + "    returns := " + egress_returns(returns, f"{where}.returns") + "\n"
        + "    generation := " + nat(generation, where) + "\n"
        + "    nextSequence := " + nat(next_sequence, where) + "\n"
        + "    pending := " + pend + "\n"
        + "    inflight := " + infl + "\n"
        + "    ackedThrough := " + opt_nat(acked_through, where) + "\n"
        + "    retry := " + egress_retry(retry, f"{where}.retry") + "\n"
        + "    invalidates := { pending := " + boolean(inv[0], where) + ", inflight := "
        + boolean(inv[1], where) + ", ackedThrough := " + boolean(inv[2], where) + ", retry := "
        + boolean(inv[3], where) + " } }"
    )


def lean_ident(name: str) -> str:
    return name.replace("-", "_")


def gen_egress(spec_dir: Path) -> str:
    sources = [spec_dir / "conformance" / "egress" / f"{name}.json" for name in EGRESS_FIXTURES]
    parts = [
        header(
            sources,
            spec_dir,
            "Kernel-checked replay of the canonical `EgressCore` corpus through\n"
            "`LazilyFormal.Egress.step`: every returned outcome, every projected field, and\n"
            "every reader invalidation of every step.",
        ),
        "",
        "import LazilyFormal.Egress",
        "",
        "namespace LazilyFormal.Conformance.EgressCorpus",
        "",
        "open LazilyFormal.Egress",
        "",
    ]
    for name, source in zip(EGRESS_FIXTURES, sources):
        where = source.name
        fixture = json.loads(source.read_text())
        _, kind, model, generation, policy, steps = take(
            fixture, "description", "kind", "model", "generation", "policy", "steps", where=where
        )
        if kind != "Egress" or model != "EgressCore":
            raise BridgeError(f"{where}: unexpected kind/model {kind!r}/{model!r}")
        limit, budget, base, ceiling = take(
            policy, "inflight_limit", "retry_budget", "retry_base", "retry_ceiling", where=f"{where}.policy"
        )
        ident = lean_ident(name)
        step_terms = [egress_step(step, f"{where}.steps[{i}]") for i, step in enumerate(steps)]
        parts += [
            f"/-- Initial core of `{where}`. -/",
            f"def {ident}_initial : State Nat :=",
            "  State.empty { inflightLimit := " + nat(limit, where) + ", retryBudget := "
            + nat(budget, where) + ", retryBase := " + nat(base, where) + ", retryCeiling := "
            + nat(ceiling, where) + " } " + nat(generation, where),
            "",
            f"/-- Every step of `{where}`. -/",
            f"def {ident}_steps : List (Expected Nat) := [",
            "  " + ",\n  ".join(step_terms),
            "]",
            "",
            f"/-- The model replays `{where}` exactly. -/",
            f"theorem {ident}_replays : replay {ident}_initial {ident}_steps = true := by decide",
            "",
        ]
    parts += ["end LazilyFormal.Conformance.EgressCorpus", ""]
    return "\n".join(parts)


