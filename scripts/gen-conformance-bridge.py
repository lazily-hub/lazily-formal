class Interner:
    """Opaque names (identities, keys, payloads, receipts) become natural numbers.

    The model only compares these for equality, so interning is a faithful
    abstraction that keeps kernel evaluation on GMP-accelerated `Nat`s."""

    def __init__(self) -> None:
        self.table: dict[str, int] = {}

    def __call__(self, value: Any, where: str) -> str:
        if not isinstance(value, str) or not value:
            raise BridgeError(f"{where}: expected a non-empty string, got {value!r}")
        return str(self.table.setdefault(value, len(self.table)))

    def opt(self, value: Any, where: str) -> str:
        return "none" if value is None else f"(some {self(value, where)})"


def gen_effect_cas(spec_dir: Path) -> str:
    source = spec_dir / "conformance" / "egress" / f"{EFFECT_CAS_FIXTURE}.json"
    where = source.name
    fixture = json.loads(source.read_text())
    _, kind, model, scenarios = take(
        fixture, "description", "kind", "model", "scenarios", optional=("$schema",), where=where
    )[:4]
    if kind != "EffectCas" or model != "EffectCasCore":
        raise BridgeError(f"{where}: unexpected kind/model {kind!r}/{model!r}")
    name = Interner()
    parts = [
        header(
            [source],
            spec_dir,
            "Kernel-checked replay of the canonical generic effect-CAS corpus through\n"
            "`LazilyFormal.EffectCas`: every returned outcome of every step and the final\n"
            "per-key projection of every scenario. Identities, keys, payloads, and receipts\n"
            "are interned to natural numbers (the model compares them only for equality);\n"
            "authority tokens are the fixture's integers. Adapter error values are opaque\n"
            "evidence and are not transcribed.",
        ),
        "",
        "import LazilyFormal.EffectCas",
        "",
        "namespace LazilyFormal.Conformance.EffectCasCorpus",
        "",
        "open LazilyFormal.EffectCas",
        "",
    ]
    names_in_order: list[tuple[str, list[str]]] = []
    for index, scenario in enumerate(scenarios):
        swhere = f"{where}.scenarios[{index}]"
        sid, generation, steps, final = take(scenario, "id", "generation", "steps", "final", where=swhere)
        saves: dict[str, int] = {}
        step_terms: list[str] = []
        for j, step in enumerate(steps):
            w = f"{swhere}.steps[{j}]"
            op, returns, save = take(step, "op", "returns", optional=("save",), where=w)
            op_term = cas_op(op, save, saves, name, w)
            step_terms.append("(" + op_term + ",\n    " + cas_returns(returns, name, w) + ")")
        final_terms = []
        for key in sorted(final):
            fw = f"{swhere}.final.{key}"
            pend, infl, applied, terminal, receipts, retry_at = take(
                final[key],
                "pending_identity",
                "inflight_identity",
                "applied_through",
                "terminal",
                "receipt_count",
                "retry_at",
                where=fw,
            )
            if terminal not in (None, "applied", "superseded", "rejected"):
                raise BridgeError(f"{fw}: unknown terminal {terminal!r}")
            term = "none" if terminal is None else f"(some .{terminal})"
            final_terms.append(
                "(" + name(key, fw) + ", { pendingIdentity := " + name.opt(pend, fw)
                + ", inflightIdentity := " + name.opt(infl, fw)
                + ", appliedThrough := " + opt_nat(applied, fw)
                + ", terminal := " + term
                + ", receiptCount := " + nat(receipts, fw)
                + ", retryAt := " + opt_nat(retry_at, fw) + " })"
            )
        ident = lean_ident(sid)
        names_in_order.append((sid, [ident]))
        parts += [
            f"/-- `{sid}`. -/",
            f"def {ident} : Scenario := {{",
            f"  generation := {nat(generation, swhere)}",
            "  steps := [\n    " + ",\n    ".join(step_terms) + "]",
            "  final := [\n    " + ",\n    ".join(final_terms) + "] }",
            "",
            f"theorem {ident}_replays : {ident}.replays = true := by decide",
            "",
        ]
    table = ", ".join(f"`{key}` = {value}" for key, value in name.table.items())
    parts.insert(
        parts.index("open LazilyFormal.EffectCas") + 2,
        f"/-! Interned names: {table}. -/\n",
    )
    parts += ["end LazilyFormal.Conformance.EffectCasCorpus", ""]
    return "\n".join(parts)


def cas_ref(value: Any, saves: dict[str, int], where: str) -> str:
    if value not in saves:
        raise BridgeError(f"{where}: attempt {value!r} was never saved by a claim")
    return str(saves[value])


def cas_op(op: Any, save: Any, saves: dict[str, int], name: Interner, where: str) -> str:
    kind = op.get("type") if isinstance(op, dict) else None
    if save is not None and kind != "claim":
        raise BridgeError(f"{where}: only a claim may save an attempt")
    if kind == "upsert":
        _, identity, key, epoch, expected, plan = take(
            op, "type", "identity", "key", "epoch", "expected", "plan", where=where
        )
        if not isinstance(plan, list) or not plan:
            raise BridgeError(f"{where}: plan must be a non-empty list")
        steps = ", ".join(name(p, where) for p in plan)
        return (
            ".upsert { identity := " + name(identity, where) + ", epoch := " + nat(epoch, where)
            + ", key := " + name(key, where) + ", expected := " + nat(expected, where)
            + ", plan := [" + steps + "] }"
        )
    if kind == "claim":
        _, key, generation, now = take(op, "type", "key", "generation", "now", where=where)
        if save is None:
            slot = "none"
        else:
            if not isinstance(save, str) or save in saves:
                raise BridgeError(f"{where}: save name {save!r} must be a fresh string")
            saves[save] = len(saves)
            slot = f"(some {saves[save]})"
        return f".claim {name(key, where)} {nat(generation, where)} {nat(now, where)} {slot}"
    if kind == "applied":
        _, key, attempt, receipt, authority = take(
            op, "type", "key", "attempt", "receipt", "authority", where=where
        )
        return (
            f".applied {name(key, where)} {cas_ref(attempt, saves, where)} "
            f"{name(receipt, where)} {nat(authority, where)}"
        )
    if kind == "superseded":
        _, key, attempt, observed, before, after = take(
            op, "type", "key", "attempt", "observed", "backend_before", "backend_after", where=where
        )
        return (
            f".superseded {name(key, where)} {cas_ref(attempt, saves, where)} "
            f"{nat(observed, where)} {nat(before, where)} {nat(after, where)}"
        )
    if kind == "retryable":
        _, key, attempt, _error, retry_at = take(
            op, "type", "key", "attempt", "error", "retry_at", where=where
        )
        return f".retryable {name(key, where)} {cas_ref(attempt, saves, where)} {nat(retry_at, where)}"
    if kind == "rejected":
        _, key, attempt, _error = take(op, "type", "key", "attempt", "error", where=where)
        return f".rejected {name(key, where)} {cas_ref(attempt, saves, where)}"
    if kind == "reconnect":
        _, generation = take(op, "type", "generation", where=where)
        return f".reconnect {nat(generation, where)}"
    raise BridgeError(f"{where}: unknown effect-CAS op {op!r}")


def cas_returns(obj: Any, name: Interner, where: str) -> str:
    if not isinstance(obj, dict) or not obj:
        raise BridgeError(f"{where}: expected a non-empty returns object")
    if "upsert" in obj:
        status = obj["upsert"]
        simple = {"accepted": ".accepted", "unchanged": ".unchanged", "epoch_conflict": ".epochConflict"}
        if status in simple:
            take(obj, "upsert", where=where)
            return f".upsert {simple[status]}"
        if status == "stale_epoch":
            _, current = take(obj, "upsert", "current", where=where)
            return f".upsert (.staleEpoch {nat(current, where)})"
        if status == "already_applied":
            _, through = take(obj, "upsert", "applied_through", where=where)
            return f".upsert (.alreadyApplied {nat(through, where)})"
    if "claim" in obj:
        status = obj["claim"]
        if status == "claimed":
            _, identity, step, attempt, expected, payload = take(
                obj, "claim", "identity", "step", "attempt", "expected", "payload", where=where
            )
            return (
                ".claim (.claimed { identity := " + name(identity, where) + ", step := "
                + nat(step, where) + ", attempt := " + nat(attempt, where) + ", expected := "
                + nat(expected, where) + ", payload := " + name(payload, where) + " })"
            )
        if status in ("busy", "empty"):
            take(obj, "claim", where=where)
            return f".claim .{status}"
        if status == "waiting":
            _, retry_at = take(obj, "claim", "retry_at", where=where)
            return f".claim (.waiting {nat(retry_at, where)})"
        if status == "stale_generation":
            _, current = take(obj, "claim", "current", where=where)
            return f".claim (.staleGeneration {nat(current, where)})"
    if "applied" in obj:
        status = obj["applied"]
        if status == "completed":
            _, through = take(obj, "applied", "applied_through", where=where)
            return f".applied (.completed {nat(through, where)})"
        if status == "step_applied":
            _, next_step = take(obj, "applied", "next_step", where=where)
            return f".applied (.stepApplied {nat(next_step, where)})"
        simple = {"duplicate": ".duplicate", "superseded": ".superseded", "unknown_attempt": ".unknownAttempt"}
        if status in simple:
            take(obj, "applied", where=where)
            return f".applied {simple[status]}"
        if status == "stale_generation":
            _, current = take(obj, "applied", "current", where=where)
            return f".applied (.staleGeneration {nat(current, where)})"
    if "failure" in obj:
        status = obj["failure"]
        simple = {"superseded": ".superseded", "rejected": ".rejected", "unknown_attempt": ".unknownAttempt"}
        if status in simple:
            take(obj, "failure", where=where)
            return f".failure {simple[status]}"
        if status == "retrying":
            _, retry_at = take(obj, "failure", "retry_at", where=where)
            return f".failure (.retrying {nat(retry_at, where)})"
        if status == "stale_generation":
            _, current = take(obj, "failure", "current", where=where)
            return f".failure (.staleGeneration {nat(current, where)})"
    if "reconnect" in obj:
        status = obj["reconnect"]
        if status == "advanced":
            _, generation, requeued, superseded = take(
                obj, "reconnect", "generation", "requeued", "superseded", where=where
            )
            return (
                f".reconnect (.advanced {nat(generation, where)} {nat(requeued, where)} "
                f"{nat(superseded, where)})"
            )
        if status == "unchanged":
            _, generation = take(obj, "reconnect", "generation", where=where)
            return f".reconnect (.unchanged {nat(generation, where)})"
        if status == "stale_generation":
            _, current = take(obj, "reconnect", "current", where=where)
            return f".reconnect (.staleGeneration {nat(current, where)})"
    raise BridgeError(f"{where}: unknown effect-CAS returns {obj!r}")


# --------------------------------------------------------------------------- #


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--spec-dir", default=str(ROOT.parent / "lazily-spec"))
    parser.add_argument("--check", action="store_true", help="fail if the generated files are stale")
    args = parser.parse_args()
    spec_dir = Path(args.spec_dir).resolve()
    if not (spec_dir / "conformance" / "egress").is_dir():
        print(
            f"error: no lazily-spec corpus at {spec_dir}; check out lazily-spec as a sibling "
            "or pass --spec-dir / LAZILY_SPEC_DIR",
            file=sys.stderr,
        )
        return 2
    egress_dir = spec_dir / "conformance" / "egress"
    known = set(EGRESS_FIXTURES) | {EFFECT_CAS_FIXTURE} | set(UNBRIDGED)
    unknown = sorted(path.stem for path in egress_dir.glob("*.json") if path.stem not in known)
    if unknown:
        print(
            f"error: conformance/egress/ has fixtures the bridge neither replays nor lists in "
            f"UNBRIDGED: {unknown}",
            file=sys.stderr,
        )
        return 1
    try:
        outputs = {
            OUT_DIR / "EgressCorpus.lean": gen_egress(spec_dir),
            OUT_DIR / "EffectCasCorpus.lean": gen_effect_cas(spec_dir),
        }
    except (BridgeError, json.JSONDecodeError, OSError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if args.check:
        if stale:
            for path in stale:
                print(f"stale: {path.relative_to(ROOT)} (run `make bridge-sync`)", file=sys.stderr)
            return 1
        print(f"conformance bridge in sync with {spec_dir} ({len(outputs)} modules)")
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in outputs.items():
        path.write_text(text)
    print(f"wrote {len(outputs)} bridge modules ({len(stale)} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
