#!/usr/bin/env python3
"""Transcribe lazily-spec conformance fixtures into kernel-checked Lean replays.

The generated modules under ``LazilyFormal/Conformance/`` carry every scenario of
the bridged fixtures as Lean data plus a ``theorem ... := by decide`` asserting
that the formal model replays it step for step (returned outcome, full projected
state, and reader invalidations). ``lake build`` therefore fails if the model
disagrees with the corpus snapshot, and ``--check`` fails if the snapshot
disagrees with the canonical corpus in ``$LAZILY_SPEC_DIR``.

This script only transcribes data. It carries no semantics: every comparison is
made by the Lean model inside the kernel. It is strict — any fixture key or
value it does not recognise is an error, so a new fixture shape can never be
silently dropped from the bridge.

Usage:
  scripts/gen-conformance-bridge.py [--spec-dir DIR] [--check]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "LazilyFormal" / "Conformance"

EGRESS_FIXTURES = [
    "egress_ordered_ack",
    "egress_inflight_window",
    "egress_retry_budget",
    "egress_generation_fence",
]
EFFECT_CAS_FIXTURE = "effect_cas"
# Fixtures in a bridged directory that are deliberately not (yet) replayed, with
# the reason. Any other unbridged file is an error, so a new fixture can never be
# silently left out of the bridge.
UNBRIDGED = {
    "latest_durable_projection": "LatestDurableProjection.lean models the pure per-key "
    "core without API outcomes; its trace replay is not bridged yet",
}


class BridgeError(Exception):
    pass


def take(obj: dict[str, Any], *keys: str, optional: tuple[str, ...] = (), where: str) -> list[Any]:
    """Return the named fields, refusing any key the bridge does not consume."""
    if not isinstance(obj, dict):
        raise BridgeError(f"{where}: expected an object, got {obj!r}")
    unknown = set(obj) - set(keys) - set(optional)
    if unknown:
        raise BridgeError(f"{where}: unrecognised keys {sorted(unknown)}")
    missing = [key for key in keys if key not in obj]
    if missing:
        raise BridgeError(f"{where}: missing keys {missing}")
    return [obj[key] for key in keys] + [obj.get(key) for key in optional]


def nat(value: Any, where: str) -> str:
    if not isinstance(value, int) or isinstance(value, bool) or value < 0:
        raise BridgeError(f"{where}: expected a natural number, got {value!r}")
    return str(value)


def opt_nat(value: Any, where: str) -> str:
    return "none" if value is None else f"(some {nat(value, where)})"


def boolean(value: Any, where: str) -> str:
    if not isinstance(value, bool):
        raise BridgeError(f"{where}: expected a boolean, got {value!r}")
    return "true" if value else "false"


def lean_list(items: list[str], indent: str) -> str:
    if not items:
        return "[]"
    inner = (",\n" + indent + "  ").join(items)
    return "[\n" + indent + "  " + inner + "\n" + indent + "]"


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def header(sources: list[Path], spec_dir: Path, module_doc: str) -> str:
    lines = [
        "/-",
        "! GENERATED by `scripts/gen-conformance-bridge.py` — do not edit by hand.",
        "",
        module_doc,
        "",
        "Regenerate with `make bridge-sync`; `make check` fails when this file no",
        "longer matches the canonical corpus. Source fixtures (sha256):",
        "",
    ]
    for source in sources:
        rel = source.relative_to(spec_dir).as_posix()
        lines.append(f"* `lazily-spec/{rel}` — `{digest(source)}`")
    lines.append("-/")
    return "\n".join(lines)


